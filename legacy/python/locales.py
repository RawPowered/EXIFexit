class I18n:
    """Simple gettext-style lookup with English fallback and format support."""

    def __init__(self, lang: str = "en") -> None:
        self._lang = "en"
        self.set_language(lang)

    @property
    def lang(self) -> str:
        return self._lang

    def set_language(self, lang: str) -> None:
        if lang not in TRANSLATIONS:
            lang = "en"
        self._lang = lang

    def t(self, key: str, **kwargs: object) -> str:
        table = TRANSLATIONS.get(self._lang, _EN)
        text = table.get(key) or _EN.get(key) or key
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text

    def __call__(self, key: str, **kwargs: object) -> str:
        return self.t(key, **kwargs)


def make_translator(lang: str = "en") -> Callable[..., str]:
    i18n = I18n(lang)
    return i18n.t
